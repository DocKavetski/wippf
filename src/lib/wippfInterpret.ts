export function pickScaleInterp(id: string, level: WippfBand): { text: string; recommendation: string; meaning: string } {
  const pack = WIPPF_INTERP[id]
  if (!pack) {
    return {
      meaning: 'Актуальная способность / измерение профиля WIPPF.',
      text: level === 'high' ? 'Выраженный полюс.' : level === 'low' ? 'Слабо выраженный полюс.' : 'Сбалансированное проявление.',
      recommendation: 'Обсудите шкалу в контексте текущих жалоб и отношений.',
    }
  }
  if (level === 'high') return { meaning: pack.meaning, text: pack.high, recommendation: pack.recHigh }
  if (level === 'low') return { meaning: pack.meaning, text: pack.low, recommendation: pack.recLow }
  return { meaning: pack.meaning, text: pack.mid, recommendation: pack.recMid }
}

/** Разница ≥ порога считается заметным перекосом (Remmers: ±2 на шкале; здесь для сумм a/r/k) */
function skew(a: number, b: number, threshold: number): boolean {
  return Math.abs(a - b) >= threshold
}

export function buildWippfRecommendations(
  scales: WippfScaleScore[],
  extremes: WippfScaleScore[],
  conflict: WippfScaleScore[],
  agg: WippfAgg[],
): string[] {
  const recs: string[] = []
  const byId = Object.fromEntries(agg.map((x) => [x.id, x.value]))
  const a = byId.a ?? 0
  const r = byId.r ?? 0
  const k = byId.k ?? 0
  const e = byId.e ?? 0
  const w = byId.w ?? 0
  const i = byId.i ?? 0

  recs.push(
    'Читайте профиль целиком: низкий и высокий балл — это полюса ценностей, а не «плохо/хорошо». Ориентир для разговора, не диагноз.',
  )

  const conflictTop = [...conflict].sort((x, y) => y.score - x.score)[0]
  if (conflictTop && conflictTop.level === 'high') {
    const tip = pickScaleInterp(conflictTop.id, 'high').recommendation
    recs.push(`Ведущая реакция на конфликт — «${conflictTop.name}». ${tip}`)
  } else if (conflictTop) {
    recs.push(
      `В конфликте относительно заметнее «${conflictTop.name}» (${conflictTop.score}/12). Имеет смысл проверить баланс четырёх сфер: тело / деятельность / контакты / фантазия.`,
    )
  }

  if (skew(k, a, 6) && k > a) {
    recs.push(
      'Идеалы (k) заметно выше собственного поведения (a): риск самокритики и внутреннего конфликта «должен — не получается». Смягчите идеалы или приблизьте поведение малыми шагами.',
    )
  } else if (skew(a, k, 6) && a > k) {
    recs.push(
      'Поведение (a) выше идеалов (k): возможны бунт против норм или обесценивание принципов. Уточните, какие нормы вы всё же хотите сохранить.',
    )
  }

  if (skew(r, a, 6) && r > a) {
    recs.push(
      'Ожидания к другим (r) выше, чем к себе (a): частый источник разочарований и претензий. Сравняйте стандарты или прямо договаривайтесь.',
    )
  }

  if (skew(w, e, 5) && w > e) {
    recs.push(
      'К другим (w) внимательнее, чем к себе (e): риск самозабвения. Верните заботу о собственных первичных потребностях (время, терпение к себе, доверие к себе).',
    )
  } else if (skew(e, w, 5) && e > w) {
    recs.push(
      'К себе (e) больше, чем к другим (w): проверьте баланс близости — не закрывает ли самоопора контакт.',
    )
  }

  if (skew(i, e, 5) && i > e) {
    recs.push(
      'Идеал отношений (i) выше самоотношения (e): часто встречается при сниженной самоценности. Укрепляйте «хорошесть» к себе, а не только идеал.',
    )
  }

  const topExtremes = extremes.slice(0, 5)
  for (const s of topExtremes) {
    const pack = pickScaleInterp(s.id, s.level)
    recs.push(`«${s.name}» (${s.score}/12, ${s.flag}): ${pack.recommendation}`)
  }

  if (extremes.length === 0) {
    recs.push(
      'Крайних шкал мало — хороший фон для работы с нюансами. Можно углубить актуальный конфликт через модель баланса и пять ступеней позитивной психотерапии.',
    )
  } else if (extremes.length >= 8) {
    recs.push(
      'Много крайних шкал: не разбирайте всё сразу. Выберите 2–3 ценности, вокруг которых сейчас больше всего напряжения в отношениях или на работе.',
    )
  }

  const polite = scales.find((s) => s.id === 'polite')
  if (polite && polite.level !== 'moderate') {
    recs.push(
      'Шкала вежливости у Пезешкиана — маркер ключевого конфликта (скрытая vs явная агрессия). Имеет смысл отдельно проговорить ситуации «не могу отказать» или «срываюсь».',
    )
  }

  recs.push(
    'На приёме полезно сравнить ваш профиль с профилем партнёра/близкого: расхождения по ценностям часто и есть содержание конфликта.',
  )

  return recs
}
